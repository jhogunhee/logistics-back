-- 출고 라인. 주문 수량만 보유하고, 할당/피킹 진행은 outb_alloc에서 집계 파생.
CREATE TABLE outb_line (
    outb_line_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outb_order_id BIGINT        NOT NULL,
    prod_id        BIGINT        NOT NULL,
    odr_qty     BIGINT        NOT NULL,
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by    VARCHAR(30)   DEFAULT 'admin' NOT NULL,
    updated_at    TIMESTAMP,
    updated_by    VARCHAR(30),
    CONSTRAINT ck_outb_line_qty CHECK (odr_qty > 0)
);

COMMENT ON TABLE  outb_line IS '출고 주문 라인. 할당/피킹 수량은 컬럼으로 두지 않고 outb_alloc 집계로 파생 (수량-상태 불일치 원천 차단)';
COMMENT ON COLUMN outb_line.odr_qty IS '주문 수량';

CREATE INDEX ix_outb_line_order ON outb_line (outb_order_id);

-- 할당. 주문라인 ↔ 재고(상품+Loc+Lot) 매핑. FEFO(+ 납품기한 필터) 결과가 기록된다.
CREATE TABLE outb_alloc (
    outb_alloc_id BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outb_line_id  BIGINT        NOT NULL,
    inv_id        BIGINT        NOT NULL,
    aloc_qty     BIGINT        NOT NULL,
    pikng_qty    BIGINT        DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by    VARCHAR(30)   DEFAULT 'admin' NOT NULL,
    updated_at    TIMESTAMP,
    updated_by    VARCHAR(30),
    CONSTRAINT ck_aloc_qty CHECK (aloc_qty > 0 AND pikng_qty >= 0 AND pikng_qty <= aloc_qty)
);

COMMENT ON TABLE  outb_alloc IS '재고 할당 레코드. 어떤 주문라인이 어떤 재고(상품+Loc+Lot)를 몇 개 예약했는지. 할당 취소 시 삭제 + inv.aloc_qty 복원';
COMMENT ON COLUMN outb_alloc.aloc_qty  IS '할당 수량 (부분할당 허용: 라인 order_qty보다 합계가 작을 수 있음)';
COMMENT ON COLUMN outb_alloc.pikng_qty IS '피킹 완료 수량. 피킹 리스트는 outb_alloc을 loc.pikng_prty 순으로 정렬한 뷰. 피킹 시 보관→SHIP-STAGE MOVE(tx PICK)와 함께 누적되고, 이때 보관 inv.alloc_qty도 소진된다(실물 반출)';

CREATE INDEX ix_alloc_line ON outb_alloc (outb_line_id);
CREATE INDEX ix_alloc_inv ON outb_alloc (inv_id);
