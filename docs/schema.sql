-- =====================================================================
-- WMS 스키마 DDL (PostgreSQL / Supabase) — 현행 기준 문서
--   스키마의 주인은 이 파일이다. 엔티티는 여기에 맞춰 작성한다.
--   신규 DB는 이 파일 전체를 적용하고, 기존 DB는 docs/migration-*.sql 증분만 적용한다.
--   (Oracle 시절 원본은 접었다 — 이력이 필요하면 커밋 히스토리를 본다)
--
-- 설계 근거: docs/design.md
--  - 재고 키: 상품 + Location + Lot
--  - 헤더 상태는 워크플로 단계만 표현, 부분 여부는 라인 수량에서 파생
--  - 재고 이력 합계 = 현재고 스냅샷 (불변식)
--  - 도메인: 식품/음료 유통센터 → 온도대 제약, 납품기한 출고 제한
--  - FK 제약은 걸지 않는다 — 참조 무결성은 애플리케이션이 보증. 서비스/DB 분리 시
--    스키마를 자유롭게 쪼갤 수 있어야 하고, 마이그레이션 순서 제약을 줄이기 위함
--
-- 네이밍 규칙
--  - 접두: 주문 OMS_* / 입고 IB_* / 출고 OUTB_* / 재고 INV* / 마스터는 무접두
--  - PK는 {테이블명}_id, FK는 참조 테이블 PK명 그대로
--  - 약어 사전 (새 컬럼도 반드시 이 사전을 따른다):
--      expected→expct  received→rcvd  rejected→rjct  putaway→ptwy
--      allocated/allocation→alloc  location→loc  history→hist
--      code→cd  name→nm  date→dt  vendor→vndr  priority→prty
--  - 공통 감사 컬럼: 모든 테이블에 created_at/created_by/updated_at/updated_by.
--    작성자는 JPA Auditing(AuditorAware)이 채운다 (인증 도입 전까지 'admin' 고정)
--
-- 참고: ddl-auto=validate이므로 Hibernate는 테이블을 만들지 않는다.
--       스키마 변경은 항상 이 파일(+증분 마이그레이션)을 DB에 먼저 적용한 뒤 엔티티를 고친다.
-- =====================================================================


-- =====================================================================
-- 1. 마스터
-- =====================================================================

-- 계량단위(UOM)는 전용 마스터 테이블을 두지 않고 공통코드 UOM 그룹으로 관리한다.
-- 정의와 시드는 아래 「공통코드」 절에 있다 (code_group 'UOM' + code_detail).
-- 화면 콤보박스도 다른 코드성 컬럼과 똑같이 /master/codes/UOM 하나로 받는다.

-- 상품 마스터. 온도대/유통기한 정책 등 "상품이 갖는 규칙"을 보유한다.
CREATE TABLE prod (
    prod_id          BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_cd          VARCHAR(30)     NOT NULL,
    prod_nm          VARCHAR(100)    NOT NULL,
    tmp_zon       VARCHAR(10)     NOT NULL,
    inb_uom_cd      VARCHAR(20)     DEFAULT 'EA' NOT NULL,
    outb_uom_cd     VARCHAR(20)     DEFAULT 'EA' NOT NULL,
    shelf_life_days INTEGER,
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by      VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at      TIMESTAMP,
    updated_by      VARCHAR(30),
    CONSTRAINT uq_prod_cd UNIQUE (prod_cd),
    CONSTRAINT ck_prod_tmp_zon CHECK (tmp_zon IN ('DRY', 'CHL', 'FRZ'))
    -- 환산수량 컬럼을 두지 않는다. 입고단위 → 출고단위 환산은 prod_uom.ea_qty(낱개수량) 두 개로
    -- 파생시킨다 (아래 prod_uom 주석 참고). 두 벌로 두면 서로 어긋날 수 있는 값이 생긴다.
);

COMMENT ON TABLE  prod IS '상품 마스터. 보관 규칙(온도대)과 유통기한 정책을 상품 단위로 정의';
COMMENT ON COLUMN prod.prod_cd          IS '상품 코드 (업무 식별자, 예: PROD-0001)';
COMMENT ON COLUMN prod.tmp_zon       IS '보관 온도대 (DRY 상온 / CHL 냉장 / FRZ 냉동). 적치·이동 시 로케이션 온도대와 일치 검증';
COMMENT ON COLUMN prod.inb_uom_cd      IS '입고단위 (prod_uom에 있는 uom_cd여야 한다, FK 없음). 벤더에게 발주하고 납품받는 단위 (예: BOX). 이 단위를 쓰는 곳은 oms_ib_line.odr_qty 하나뿐이다. CHECK를 걸지 않는 이유는 값 목록의 주인이 공통코드 UOM 그룹이라서, CHECK가 있으면 단위를 추가할 때마다 DDL을 고쳐야 하기 때문 (zon.tmp_zon 등과 같은 형태)';
COMMENT ON COLUMN prod.outb_uom_cd     IS '출고단위 (prod_uom에 있는 uom_cd여야 한다, FK 없음). 재고 저장 단위이기도 하다 — inv · inv_hist · ib_line · putaway_task · outb_line · outb_alloc 의 모든 수량 컬럼이 이 단위다 (oms_ib_line.odr_qty만 예외)';
COMMENT ON COLUMN prod.shelf_life_days IS '제조일 기준 총 유통기한(일). NULL = 유통기한 미관리(공산품 등). 시더가 Lot 유통기한 생성 시 사용';

-- 상품 코드(PROD-0001)는 채번 모듈이 발급한다 — nbr_rule 'PROD_CD' + nbr_seq.
-- 전용 시퀀스(prod_cd_seq)를 두던 방식은 폐기했다. 규칙이 테이블 데이터라 화면에서 바꿀 수 있고,
-- 일자 리셋 같은 패턴도 DDL 없이 표현된다 (아래 「채번」 절 참고).

-- 상품 포장. (상품, 단위) 한 조합이 한 행이다 — 한 상품이 낱개·박스·파렛트를 동시에 갖고,
-- 낱개수량과 중량은 그 조합마다 다르다.
--
-- 환산수량 컬럼(prod.cnvr_qty) 대신 이 테이블을 두는 이유 —
--   ① 상품당 한 칸이면 "입고단위 → 출고단위" 한 쌍만 표현된다. 박스·파렛트를 함께 다루려면
--      쌍마다 컬럼이 늘어난다. 낱개수량을 단위마다 두면 어떤 두 단위든 낱개를 매개로 환산된다
--      (BOX→EA = ea_qty(BOX) / ea_qty(EA)).
--   ② 중량을 둘 자리가 여기 말고 없다. prod에 두면 그 값이 어느 포장 기준인지 이름에 드러나지 않고,
--      박스 중량을 「낱개중량 × 낱개수량」으로 파생하게 되어 포장재 무게(tare)가 사라진다.
--      파렛트처럼 tare가 큰 단위에서 무시할 수 없는 오차다.
--
-- PK는 규칙대로 prod_uom_id 대리키이고, 실제 grain은 uq_prod_uom이 강제한다.
-- prod_id는 FK가 아니다 (FK 0건 정책) — 상품 삭제 시 포장 정리는 ProdService(cascade)가 한다.
CREATE TABLE prod_uom (
    prod_uom_id BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_id     BIGINT          NOT NULL,
    uom_cd      VARCHAR(20)     NOT NULL,
    ea_qty      BIGINT          NOT NULL,
    wgt         NUMERIC(12, 3),
    created_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by  VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR(30),
    CONSTRAINT uq_prod_uom UNIQUE (prod_id, uom_cd),
    -- 0이나 음수면 환산이 수량을 0으로 만들거나 부호를 뒤집는다. 단위 관련 유일한 DB 방어선이다
    CONSTRAINT ck_prod_uom_ea_qty CHECK (ea_qty >= 1),
    -- NULL은 미측정. 값이 있는데 0 이하면 실측값일 수 없다
    CONSTRAINT ck_prod_uom_wgt CHECK (wgt IS NULL OR wgt > 0)
);

COMMENT ON TABLE  prod_uom IS '상품 포장. (상품, 단위) 한 조합이 한 행 — 낱개수량과 중량을 포장마다 갖는다. 입고→출고단위 환산이 여기서 파생된다';
COMMENT ON COLUMN prod_uom.uom_cd IS '단위 코드. 공통코드 UOM 그룹(code_detail) 참조, FK 없음 — 존재 검증은 ProdService';
COMMENT ON COLUMN prod_uom.ea_qty IS '이 단위 1개가 낱개 몇 개인가 (예: BOX 1개 = 24). 낱개 그 자체면 1. 환산은 OmsIbOrderService.convert(발주→ASN) 한 곳에서만 일어나고 — odr_qty × ea_qty(입고단위) / ea_qty(출고단위) — ASN 이후의 검수·적치·재고·출고는 전부 출고단위로만 계산한다';
COMMENT ON COLUMN prod_uom.wgt    IS '이 단위 1개의 중량(kg). 포장재 무게(tare)를 포함한 실측값이며 미측정이면 NULL. 낱개중량 × 낱개수량으로 파생시키지 않는 이유가 tare다';

-- 존 마스터. 로케이션의 상위 그룹 (온도 · 보관형태 · 담당업무 단위).
-- tmp_zon은 loc.tmp_zon · prod.tmp_zon과 같은 값 도메인이다 (공통코드 TEMP_ZONE, Java TempZone enum 공용).
-- tmp_zon / strg_typ / biz_dvsn은 공통코드에서 관리하므로 CHECK를 걸지 않는다 —
-- 코드를 추가할 때마다 DDL을 고치지 않기 위함이고, 값 검증은 서비스단 enum이 맡는다.
-- (loc·prod는 CHECK를 갖고 있어 존만 방식이 다르다. 근거는 docs/design.md 「존 마스터」)
CREATE TABLE zon (
    zon_id      BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zon_cd      VARCHAR(20)     NOT NULL,
    zon_nm      VARCHAR(100)    NOT NULL,
    tmp_zon     VARCHAR(10)     NOT NULL,
    strg_typ    VARCHAR(10)     NOT NULL,
    biz_dvsn    VARCHAR(10)     NOT NULL,
    created_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by  VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR(30),
    CONSTRAINT uq_zon_cd UNIQUE (zon_cd)
);

COMMENT ON TABLE  zon IS '존 마스터. 로케이션의 상위 그룹 (loc.zon_cd가 zon.zon_cd를 느슨하게 참조)';
COMMENT ON COLUMN zon.zon_cd   IS '존 코드 (업무 식별자, 예: DRY, RCV-STAGE). 하위 로케이션이 문자열로 참조하므로 등록 후 변경 금지';
COMMENT ON COLUMN zon.zon_nm   IS '존 명 (화면 표시용)';
COMMENT ON COLUMN zon.tmp_zon  IS '온도구분. 공통코드 TEMP_ZONE (DRY 상온 / CHL 냉장 / FRZ 냉동). 보관 로케이션은 이 값과 loc.tmp_zon이 일치해야 한다';
COMMENT ON COLUMN zon.strg_typ IS '보관유형. 공통코드 STRG_TYP (RACK 랙 / FLAT 평치 / VRTL 가상)';
COMMENT ON COLUMN zon.biz_dvsn IS '업무구분. 공통코드 BIZ_DVSN (INB 입고작업 / OUTB 출고작업 / STRG 보관 / PIKNG 피킹 / RTNGS 반품 / WRK 작업)';

-- 로케이션 마스터. 존(zon)의 하위 물리 위치. 입고 스테이징(RCV-STAGE)과 온도대별 보관존으로 구성.
CREATE TABLE loc (
    loc_id          BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loc_cd          VARCHAR(30)     NOT NULL,
    zon_cd         VARCHAR(20)     NOT NULL,
    tmp_zon       VARCHAR(10)     NOT NULL,
    loc_typ        VARCHAR(10)     NOT NULL,
    pikng_prty       INTEGER         DEFAULT 0 NOT NULL,
    max_qty         BIGINT,
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by      VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at      TIMESTAMP,
    updated_by      VARCHAR(30),
    CONSTRAINT uq_loc_cd UNIQUE (loc_cd),
    CONSTRAINT ck_loc_tmp_zon CHECK (tmp_zon IN ('DRY', 'CHL', 'FRZ')),
    CONSTRAINT ck_loc_typ CHECK (loc_typ IN ('STAGE', 'STORAGE')),
    CONSTRAINT ck_loc_max_qty CHECK (max_qty IS NULL OR max_qty > 0),
    -- 용량은 적치 전략의 전제다. 보관 로케이션에 상한이 없으면 후보가 "온도대 일치 전부"라
    -- 전략이 정렬 순서밖에 바꾸지 못한다 — 그래서 STORAGE에만 NOT NULL을 강제한다.
    CONSTRAINT ck_loc_storage_capacity CHECK (loc_typ <> 'STORAGE' OR max_qty IS NOT NULL)
);

COMMENT ON TABLE  loc IS '로케이션 마스터. 재고가 놓이는 물리 위치 (스테이징/보관존)';
COMMENT ON COLUMN loc.loc_cd    IS '로케이션 코드 (예: DRY-A-01-01, RCV-STAGE)';
COMMENT ON COLUMN loc.zon_cd   IS '존 코드. zon.zon_cd를 참조하지만 FK는 없다 — 존재 검증은 LocService가 한다';
COMMENT ON COLUMN loc.tmp_zon IS '존 온도대. 상품 온도대와 불일치하면 적치·이동 차단 (스테이징은 예외적으로 전 온도대 허용할지 서비스에서 판단)';
COMMENT ON COLUMN loc.loc_typ  IS 'STAGE: 스테이징(RCV-STAGE 적치 대기 / SHIP-STAGE 반출 대기) / STORAGE: 보관(할당 대상)';
COMMENT ON COLUMN loc.pikng_prty IS '할당 시 동일 유통기한(FEFO 동순위) 간 로케이션 우선순위. 낮을수록 먼저 할당. 적치 지시의 후보 순회 순서이기도 하다';
COMMENT ON COLUMN loc.max_qty   IS '최대 적재 수량. 적재가능수량 = max_qty - 현재고 - 미완료 지시 잔량. NULL = 무제한(스테이징 전용), STORAGE는 NOT NULL 강제';

-- Lot. 입고 처리 시점에 생성되며 유통기한을 보유한다 (FEFO 기준값).
CREATE TABLE lot (
    lot_id      BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_id      BIGINT          NOT NULL,
    lot_no      VARCHAR(30)     NOT NULL,
    receipt_dt  DATE,
    mfg_dt      DATE,
    expiry_dt   DATE,
    created_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by  VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR(30),
    CONSTRAINT uq_lot UNIQUE (prod_id, lot_no)
);

COMMENT ON TABLE  lot IS 'Lot(입고 단위 묶음). 입고 처리 시 생성. 유통기한이 FEFO 할당과 납품기한 필터의 기준';
COMMENT ON COLUMN lot.lot_no    IS 'Lot 번호 (상품 내 유일). 입고일 기준 상품별 일자 리셋 채번(LOT-YYMMDD-NNN). 유통기한 미관리 상품도 동일 형식이며 입고일자만으로 구분됨';
COMMENT ON COLUMN lot.receipt_dt IS '입고일자 (소급 등록 가능). 상품+입고일자+제조일자가 같으면 기존 Lot을 재사용 (증분 검수 시 배치 중복 생성 방지). 유통기한 미관리 상품은 제조일자가 항상 NULL이라 사실상 상품+입고일자로만 구분';
COMMENT ON COLUMN lot.mfg_dt    IS '제조일자. 유통기한 미관리 상품의 Lot은 NULL';
COMMENT ON COLUMN lot.expiry_dt IS '유통기한. 생성 시점의 prod.shelf_life_days로 계산해 저장한 스냅샷 (이후 상품 마스터 변경에 소급 영향 없음). NULL = 미관리 상품의 Lot (FEFO 맨 뒤 정렬, 잔여수명 필터 대상 아님)';

CREATE INDEX ix_lot_expiry ON lot (prod_id, expiry_dt);
-- Lot 재사용 조회(상품+입고일자+제조일자) 및 일자별 채번 카운트에 사용
CREATE INDEX ix_lot_prod_receipt ON lot (prod_id, receipt_dt);

-- Lot 번호는 더 이상 DB 시퀀스로 채번하지 않는다.
-- 상품 로우 락(SELECT ... FOR UPDATE) 하에 해당 상품+입고일자의 기존 Lot 건수를 세어 다음 번호를 매긴다 (상품별 일자 리셋).

-- 점포 마스터. 납품 기준(잔여수명 허용률)은 상품이 아니라 납품처가 정한다.
CREATE TABLE store (
    store_id        BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_cd        VARCHAR(30)     NOT NULL,
    store_nm        VARCHAR(100)    NOT NULL,
    outb_life_rate  SMALLINT        DEFAULT 40 NOT NULL,
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by      VARCHAR(30)     DEFAULT 'admin' NOT NULL,
    updated_at      TIMESTAMP,
    updated_by      VARCHAR(30),
    CONSTRAINT uq_store_cd UNIQUE (store_cd),
    CONSTRAINT ck_store_life_rate CHECK (outb_life_rate BETWEEN 0 AND 100)
);

COMMENT ON TABLE  store IS '점포(납품처) 마스터. 납품 허용 잔여수명 기준을 점포 단위로 관리';
COMMENT ON COLUMN store.store_cd       IS '점포 코드 (업무 식별자, 예: ST-0001)';
COMMENT ON COLUMN store.outb_life_rate IS '납품 허용 잔여수명 비율(%). 이 점포 출고 시 잔여 유통기한이 이 비율 미만인 Lot은 할당 제외 (FEFO 앞단 필터)';

-- 벤더(납품처) 마스터. 입고주문·입고예정이 참조한다.
