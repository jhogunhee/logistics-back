--    ASN 쪽도 취소 상태를 두지 않는다: 확정취소는 ASN 행을 삭제한다 — 검수 전의 예정은
--    아직 아무 일도 안 한 문서라 흔적 가치가 없다 (재확정하면 새 번호로 새 행이 생긴다).
