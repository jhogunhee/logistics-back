COMMENT ON COLUMN wav_stgy.prty         IS '실행 순서';
COMMENT ON COLUMN wav_stgy.cond_grp     IS '조건그룹 [[{fld,op,vals},…],…]. 그룹끼리 OR, 그룹 안 AND';
COMMENT ON COLUMN wav_stgy.last_rvsn_no IS '마지막 저장 리비전';


-- 할당 전략. 자동할당의 "어느 재고를, 어떤 순서로, 모자라면 누구에게"를 슬롯 단위로 정의한다.
-- 다른 세 유형과 다른 점: 할당에는 이미 코드에 박힌 기본 동작(FEFO + 점포 잔여수명 + 순차 소진)이
-- 있어서, 전략은 없던 판단을 만드는 게 아니라 그 기본값을 슬롯 단위로 덮어쓴다.
-- 그래서 필수 슬롯이 없고, 전략이 0건이면 기존 동작이 그대로 유지된다.
CREATE TABLE aloc_stgy (
    aloc_stgy_id BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stgy_nm      VARCHAR(100) NOT NULL,
    prty         INTEGER      DEFAULT 0 NOT NULL,
    tgt_cond     JSONB        DEFAULT '[]' NOT NULL,
    last_rvsn_no BIGINT       DEFAULT 1 NOT NULL,
    created_at   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by   VARCHAR(30)  DEFAULT 'admin' NOT NULL,
    updated_at   TIMESTAMP,
    updated_by   VARCHAR(30),
    CONSTRAINT ck_aloc_stgy_prty     CHECK (prty >= 0),
    -- 웨이브(cond_grp)와 달리 길이 CHECK가 없다 — 할당의 조건 0건은 사고가 아니라
    -- "어느 전략도 매칭되지 않을 때 무엇을 쓸지"를 뜻하는 전체 매칭 폴백 전략이다
    CONSTRAINT ck_aloc_stgy_tgt_cond CHECK (jsonb_typeof(tgt_cond) = 'array')
);

COMMENT ON TABLE  aloc_stgy IS '할당 전략';
COMMENT ON COLUMN aloc_stgy.stgy_nm      IS '전략명';
COMMENT ON COLUMN aloc_stgy.prty         IS '선택 순서';
COMMENT ON COLUMN aloc_stgy.tgt_cond     IS '적용대상 조건 [{fld,op,vals},…]. 빈 배열 = 전체';
COMMENT ON COLUMN aloc_stgy.last_rvsn_no IS '마지막 저장 리비전';


-- 할당 슬롯. 적치 단계와 같은 판단으로 JSONB가 아니라 행이다 —
-- 개별로 추가·삭제·순서변경(drag&drop)하고 자기 파라미터·조건을 갖는 편집 단위이기 때문.
CREATE TABLE aloc_stgy_slot (
    aloc_stgy_slot_id BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aloc_stgy_id      BIGINT      NOT NULL,
    slot_typ          VARCHAR(15) NOT NULL,
    srt_seq           INTEGER     DEFAULT 0 NOT NULL,
    cmpnt_cd          VARCHAR(30),
    para              JSONB       DEFAULT '{}' NOT NULL,
    cond              JSONB       DEFAULT '[]' NOT NULL,
    created_at        TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by        VARCHAR(30) DEFAULT 'admin' NOT NULL,
    updated_at        TIMESTAMP,
    updated_by        VARCHAR(30),
    CONSTRAINT ck_aloc_slot_typ CHECK (
        slot_typ IN ('INVN_FLTR','RSTRCT','INVN_SRT','ODR_SRT','DSTRB')
    ),
    -- 구현체 축이 있는 슬롯은 RSTRCT·DSTRB뿐이다. 필터 슬롯은 "무엇을 실행할지"가 아니라
    -- "어느 후보만"을 정하므로 정의 전체가 cond이고, 정렬 슬롯은 "기준을 순서대로 나열"
    -- 하나뿐이라 para.criteria가 정의 전부다 — 둘 다 고를 구현체가 없다.
    CONSTRAINT ck_aloc_slot_cmpnt CHECK (
        (slot_typ IN ('INVN_FLTR','INVN_SRT','ODR_SRT') AND cmpnt_cd IS NULL)
     OR (slot_typ IN ('RSTRCT','DSTRB')                 AND cmpnt_cd IS NOT NULL)
    ),
    CONSTRAINT ck_aloc_slot_srt_seq CHECK (srt_seq >= 0),
    CONSTRAINT ck_aloc_slot_para    CHECK (jsonb_typeof(para) = 'object'),
    CONSTRAINT ck_aloc_slot_cond    CHECK (jsonb_typeof(cond) = 'array')
);

CREATE INDEX ix_aloc_stgy_slot ON aloc_stgy_slot (aloc_stgy_id);
-- 단일 슬롯에 2건 등록을 DB가 거부한다. 다중 슬롯(INVN_FLTR·RSTRCT·DSTRB)은 대상이 아니다 —
-- 계층·순서를 표현하는 것이 그 슬롯들의 존재 이유이기 때문.
CREATE UNIQUE INDEX uq_aloc_stgy_slot_single ON aloc_stgy_slot (aloc_stgy_id, slot_typ)
    WHERE slot_typ IN ('INVN_SRT','ODR_SRT');

COMMENT ON TABLE  aloc_stgy_slot IS '할당 슬롯 (역할 5종)';
COMMENT ON COLUMN aloc_stgy_slot.aloc_stgy_id IS '할당 전략 헤더';
COMMENT ON COLUMN aloc_stgy_slot.slot_typ     IS '슬롯 유형. AlocSlotTyp enum';
COMMENT ON COLUMN aloc_stgy_slot.srt_seq      IS '다중 슬롯 안의 순서';
COMMENT ON COLUMN aloc_stgy_slot.cmpnt_cd     IS '구현체 code (enum name). 구현체 축이 없는 슬롯은 NULL';
COMMENT ON COLUMN aloc_stgy_slot.para         IS '슬롯 파라미터 [{"field","dir"},…]';
COMMENT ON COLUMN aloc_stgy_slot.cond         IS '슬롯 조건 [{fld,op,vals},…]';
