--    확정취소하면 작업문서는 삭제되고 주문은 CREATED로 돌아와 재확정할 수 있다.
--
--    취소 상태를 두지 않는다. 없앨 주문은 지운다 — 확정 전이면 바로, 확정 뒤면 확정취소로
--    되돌린 뒤에. "지운 것도 아니고 쓰는 것도 아닌" 상태를 두면 목록·집계마다 그 상태를 빼는
--    필터가 따라붙고, 화면에서 삭제와 취소 중 무엇을 눌러야 하는지가 매번 애매해진다.
